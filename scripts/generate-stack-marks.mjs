/**
 * Writes `src/data/stack-marks.ts` from the `simple-icons` package.
 *
 * The marks are needed in two places — the stack strip (server) and the hero
 * cube (client) — so they are generated into a plain data module instead of
 * importing the 3,000-icon package at runtime. Re-run with `pnpm run icons`
 * after editing the list below.
 */
import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

/** [export name, label override] — the order the strip renders them in. */
const WANTED = [
  ["siReact"],
  ["siNextdotjs"],
  ["siTypescript"],
  ["siJavascript"],
  ["siTailwindcss"],
  ["siTanstack", "TanStack Query"],
  [null, "Zustand"],
  ["siRedux", "Redux Toolkit"],
  ["siGsap"],
  ["siFramer", "Framer Motion"],
  ["siThreedotjs"],
  ["siNodedotjs"],
  ["siGit"],
];

/**
 * Brand colours are authored for light backgrounds, and the near-black ones
 * would read as holes on this site — those fall back to the foreground.
 */
function onDark(hex) {
  const value = Number.parseInt(hex, 16);
  const r = (value >> 16) & 255;
  const g = (value >> 8) & 255;
  const b = value & 255;
  const luminance = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
  return luminance < 0.25 ? "#f4f4f5" : `#${hex}`;
}

const marks = WANTED.map(([key, label]) => {
  if (!key) return { label, color: "#f4f4f5" };

  const icon = icons[key];
  if (!icon) throw new Error(`simple-icons has no export "${key}"`);
  return {
    label: label ?? icon.title,
    path: icon.path,
    color: onDark(icon.hex),
  };
});

const body = `// Generated by scripts/generate-stack-marks.mjs — do not edit by hand.
// Run \`pnpm run icons\` to regenerate.

export type StackMark = {
  label: string;
  /** Path data for a 24×24 viewBox. Absent when there is no brand mark. */
  path?: string;
  color: string;
};

export const stackMarks: StackMark[] = ${JSON.stringify(marks, null, 2)};
`;

writeFileSync(new URL("../src/data/stack-marks.ts", import.meta.url), body);
console.log(`wrote ${marks.length} marks`);
